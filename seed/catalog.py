"""Synthetic seed data for the public catalog (categories, events).

All events are fictional. Dates are offsets relative to "today" so that the data never
goes stale: e.g. `start=-3, days=10` is an event that started three days ago and runs for
ten days. IDs are deterministic (uuid5) so reseeding keeps deep links stable.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from uuid import NAMESPACE_URL, UUID, uuid5


def seed_id(kind: str, key: str) -> UUID:
    """Deterministic ID for a seed entity."""
    return uuid5(NAMESPACE_URL, f"https://stadtfest-finder.de/seed/{kind}/{key}")


@dataclass(frozen=True)
class SeedCategory:
    key: str
    name: str
    emoji: str
    color: str
    active: bool = True


@dataclass(frozen=True)
class SeedProgramItem:
    day: int  # offset from the event start
    time_label: str
    title: str
    subtitle: str | None = None


@dataclass(frozen=True)
class SeedEvent:
    key: str
    name: str
    short_name: str
    category: str | None
    status: str  # draft | published | cancelled
    start: int | None  # offset from today
    days: int  # duration in days (1 = one-day event)
    place: str
    address: str
    city: str
    postal_code: str
    lat: float | None
    lon: float | None
    opening_hours: tuple[str, ...] = ()
    price: str | None = None
    description: str | None = None
    transit: str | None = None
    parking: str | None = None
    website_url: str | None = None
    cancel_reason: str | None = None
    source: str = "manual"
    source_url: str | None = None
    program: tuple[SeedProgramItem, ...] = field(default_factory=tuple)


